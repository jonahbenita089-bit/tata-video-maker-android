import os
from typing import Any, Dict

import httpx


class HuggingFaceVideoService:
    def __init__(self, token: str = "", model_name: str = ""):
        self.token = token or os.getenv("HF_TOKEN", "")
        self.model_name = model_name or os.getenv("HF_TEXT_TO_VIDEO_MODEL", "")
        self.base_url = "https://api-inference.huggingface.co/models"

    async def generate_video(
        self,
        prompt: str,
        duration_seconds: int = 15,
        style: str = "cinematic",
        aspect_ratio: str = "16:9",
    ) -> Dict[str, Any]:
        if not self.token or not self.model_name:
            return {
                "success": False,
                "is_mock": True,
                "message": "Hugging Face token/model not configured.",
            }

        headers = {
            "Authorization": f"Bearer {self.token}",
            "Content-Type": "application/json",
        }

        payload = {
            "inputs": prompt,
            "parameters": {
                "num_frames": max(8, int(duration_seconds * 4)),
                "guidance_scale": 7.5,
                "num_inference_steps": 30,
                "width": 768,
                "height": 432,
            },
            "options": {"wait_for_model": True},
        }

        try:
            async with httpx.AsyncClient(timeout=300) as client:
                response = await client.post(
                    f"{self.base_url}/{self.model_name}",
                    headers=headers,
                    json=payload,
                )

                if response.status_code >= 400:
                    return {
                        "success": False,
                        "error": f"HF error {response.status_code}",
                        "details": response.text,
                    }

                data = response.json()

                return {
                    "success": True,
                    "is_mock": False,
                    "message": "Video generated by Hugging Face model.",
                    "prompt": prompt,
                    "duration_seconds": duration_seconds,
                    "style": style,
                    "aspect_ratio": aspect_ratio,
                    "result": data,
                }
        except Exception as exc:
            return {
                "success": False,
                "error": str(exc),
                "message": "Failed to call Hugging Face model.",
            }
